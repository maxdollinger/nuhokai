import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";

/** Where the generated asset lives; the test reads it, the CLI imports it. */
export const GENERATED_FILE = join(import.meta.dir, "../src/toolchain/world-types.gen.ts");

/** The repo's pinned checker; the test runs it against a consumer world. */
export const TSC = join(import.meta.dir, "../../../node_modules/.bin/tsc");

const WORLD_ENTRY = join(import.meta.dir, "../../../packages/world/src/index.ts");
const BASE_TSCONFIG = join(import.meta.dir, "../../../tsconfig.base.json");
const HEADER = "// Generated by packages/cli/scripts/embed-world.ts. Do not edit.\n";
const BUNDLE_HEADER = `${HEADER}// The self-contained @nuhokai/world declarations, bundled for nuhokai/.generated/world/index.d.ts.\n\n`;

/** Emit @nuhokai/world's declarations into a temporary directory and return them by file name. */
function emitDeclarations(): Map<string, string> {
  const dir = mkdtempSync(join(tmpdir(), "nuhokai-world-dts-"));
  try {
    const outDir = join(dir, "dts");
    const project = join(dir, "tsconfig.json");
    writeFileSync(
      project,
      JSON.stringify({
        extends: BASE_TSCONFIG,
        compilerOptions: {
          noEmit: false,
          declaration: true,
          emitDeclarationOnly: true,
          noEmitOnError: true,
          outDir,
          rootDir: dirname(WORLD_ENTRY),
          types: [],
        },
        include: [],
        files: [WORLD_ENTRY],
      }),
    );

    const result = Bun.spawnSync([TSC, "-p", project, "--pretty", "false"]);
    if (result.exitCode !== 0) {
      throw new Error(`tsc failed to emit @nuhokai/world declarations:\n${result.stdout}${result.stderr}`);
    }

    const files = readdirSync(outDir).filter((file) => file.endsWith(".d.ts"));
    return new Map(files.sort().map((file) => [file, readFileSync(join(outDir, file), "utf8")] as const));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Inline one emitted module into the bundle: drop its `import type` lines (their
 * targets are concatenated into the same file) and its `export … from` re-exports.
 * In node-spec.d.ts also strip `export `, so types.ts's `export type { NodeId }`
 * re-export binds to the inlined declaration instead of the dropped import.
 */
function inlineModule(file: string, content: string): string {
  const kept: string[] = [];
  for (const line of content.split("\n")) {
    const trimmed = line.trimStart();
    if (trimmed.startsWith("import ")) {
      if (!trimmed.trimEnd().endsWith(";")) throw new Error(`multiline import in ${file}`);
      continue;
    }
    if (/^export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s+"/.test(trimmed)) continue;
    if (/^export\s*\{\s*\};?\s*$/.test(trimmed)) continue;
    kept.push(line);
  }

  let text = kept
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  if (file === "node-spec.d.ts") {
    text = text
      .split("\n")
      .map((line) => (line.startsWith("export ") ? line.slice("export ".length) : line))
      .join("\n");
  }
  return text;
}

/**
 * Bundle the emitted declarations into one self-contained `.d.ts` string.
 * The barrel `index.d.ts` holds nothing but re-exports, which inlining drops.
 * Declaration files are type-only, so concatenation order does not matter;
 * the sorted order is for determinism only.
 */
export function renderWorldTypes(files: Map<string, string> = emitDeclarations()): string {
  const modules = [...files.entries()]
    .filter(([file]) => file !== "index.d.ts")
    .map(([file, content]) => `// ─── ${file} ───\n${inlineModule(file, content)}`);
  return `${BUNDLE_HEADER}${modules.join("\n\n")}\n`;
}

/** Render the generated TS module the CLI imports at runtime. */
export function renderGeneratedModule(worldTypes: string = renderWorldTypes()): string {
  return `${HEADER}// The self-contained @nuhokai/world declarations.\nexport const WORLD_TYPES: string = ${JSON.stringify(worldTypes)};\n`;
}

/** Write the generated asset; `unchanged` when it is already byte-identical. */
export function writeWorldTypes(): "written" | "unchanged" {
  const generated = renderGeneratedModule();
  if (existsSync(GENERATED_FILE) && readFileSync(GENERATED_FILE, "utf8") === generated) return "unchanged";

  mkdirSync(dirname(GENERATED_FILE), { recursive: true });
  writeFileSync(GENERATED_FILE, generated);
  return "written";
}

if (import.meta.main) {
  const path = relative(join(import.meta.dir, "../../.."), GENERATED_FILE);
  console.log(writeWorldTypes() === "written" ? `world types: wrote ${path}` : `world types: ${path} is up to date`);
}
