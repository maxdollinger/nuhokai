import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

/** Where the generated asset lives; the test reads it, MapFile imports it. */
export const GENERATED_FILE = join(import.meta.dir, "../src/toolchain/map-assets.gen.ts");

/** The exact three.js release the map inlines; package.json pins the same version. */
export const THREE_VERSION = "0.186.1";

const MAP_DIR = join(import.meta.dir, "../src/map");
const HEADER = "// Generated by packages/cli/scripts/embed-map.ts. Do not edit.\n";

/** The installed three package's directory, after checking it is the pinned release. */
function threeDir(): string {
  const manifest = Bun.resolveSync("three/package.json", import.meta.dir);
  const { version } = JSON.parse(readFileSync(manifest, "utf8")) as { version?: string };
  if (version !== THREE_VERSION) {
    throw new Error(`three ${version} is installed, the map pins ${THREE_VERSION}; run bun install`);
  }
  return dirname(manifest);
}

/**
 * The names the viewer reads off THREE, so the bundle keeps exactly those. Every
 * `THREE.<name>` in viewer.html counts, comments too, so prose there must not write one.
 */
function threeNames(viewer: string): string[] {
  return [...new Set(Array.from(viewer.matchAll(/\bTHREE\.(\w+)/g), ([, name]) => name as string))].sort();
}

/**
 * three.js and OrbitControls as one classic script that sets the global THREE
 * the viewer reads, cut down to the names it uses; three.js ships both only as
 * ES modules. Headed by three's own license block.
 */
async function threeBundle(three: string, viewer: string): Promise<string> {
  const names = threeNames(viewer);
  const core = names.filter((name) => name !== "OrbitControls");
  const entry = join(MAP_DIR, "three-entry.js");
  const build = await Bun.build({
    entrypoints: [entry],
    files: {
      [entry]: `import { ${core.join(", ")} } from "three";
import { OrbitControls } from "three/examples/jsm/controls/OrbitControls.js";
globalThis.THREE = { ${names.join(", ")} };
`,
    },
    format: "iife",
    target: "browser",
    minify: true,
  });
  const [output] = build.outputs;
  if (!build.success || !output) throw new AggregateError(build.logs, "bundling three.js failed");
  const license = readFileSync(join(three, "build/three.core.js"), "utf8").match(
    /^\/\*\*\n \* @license[\s\S]*?\*\/\n/,
  )?.[0];
  if (!license) throw new Error("three.js's license block is missing from build/three.core.js");
  return license + (await output.text());
}

/** The three texts the map is assembled from: three.js with OrbitControls, the viewer page and the scene module. */
async function mapAssets(): Promise<Record<"THREE_JS" | "VIEWER_HTML" | "SCENE_JS", string>> {
  const viewer = readFileSync(join(MAP_DIR, "viewer.html"), "utf8");
  return {
    THREE_JS: await threeBundle(threeDir(), viewer),
    VIEWER_HTML: viewer,
    SCENE_JS: readFileSync(join(MAP_DIR, "scene.js"), "utf8"),
  };
}

/** A template literal whose value is exactly `text`, so the generated file keeps the assets' lines readable. */
function literal(text: string): string {
  return `\`${text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${").replaceAll("\r", "\\r")}\``;
}

/** Render the generated TS module the CLI imports at runtime. */
export async function renderMapAssets(): Promise<string> {
  const assets = await mapAssets();
  const exports = Object.entries(assets).map(([name, text]) => `export const ${name}: string = ${literal(text)};\n`);
  return `${HEADER}// The map's assets: three.js ${THREE_VERSION} with OrbitControls under three's license header, the viewer page and the scene module.\n\n${exports.join("\n")}`;
}

/** Write the generated asset; `unchanged` when it is already byte-identical. */
export async function writeMapAssets(): Promise<"written" | "unchanged"> {
  const generated = await renderMapAssets();
  if (existsSync(GENERATED_FILE) && readFileSync(GENERATED_FILE, "utf8") === generated) return "unchanged";

  mkdirSync(dirname(GENERATED_FILE), { recursive: true });
  writeFileSync(GENERATED_FILE, generated);
  return "written";
}

if (import.meta.main) {
  const path = relative(join(import.meta.dir, "../../.."), GENERATED_FILE);
  console.log(
    (await writeMapAssets()) === "written" ? `map assets: wrote ${path}` : `map assets: ${path} is up to date`,
  );
}
